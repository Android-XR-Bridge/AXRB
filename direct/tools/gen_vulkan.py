"""Generates AXRB Direct's Vulkan forwarding tables from the NDK's Vulkan headers.

    python direct/tools/gen_vulkan.py <ndk-sysroot-include-dir>

Writes
  direct/guest/proxy/vk_thunks.inc  guest libvulkan.so: one exported function per
                                    command that packs its arguments into uint64_t
                                    slots and traps to the host ("vk.call", id)
  direct/src/vk_entries.inc         host: command names, dispatch level and an
                                    invoker that unpacks the slots into the host
                                    driver's function

Both sides index commands by their position in the same list, so they must be
regenerated together. Guest and host structures share their layout (LP64 and
LLP64 agree on every Vulkan type: no `long`), so only the arguments are
marshalled; pointers are identity-mapped.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADERS = ["vulkan/vulkan_core.h", "vulkan/vulkan_android.h"]
# The loader's own entry points: written by hand on both sides.
MANUAL = {"vkGetInstanceProcAddr", "vkGetDeviceProcAddr"}

PROTO = re.compile(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\)\s*;", re.S)


def parse_param(text):
    text = " ".join(text.split())
    m = re.match(r"(.*?)\b(\w+)\s*((?:\[\w+\])*)$", text)
    if not m:
        raise SystemExit("cannot parse parameter: " + text)
    ctype, name, dims = m.group(1).strip(), m.group(2), m.group(3)
    if dims:
        ctype += "*"
    return ctype, name


def level(params):
    if not params:
        return "kGlobal"
    first = params[0][0]
    if first in ("VkInstance", "VkPhysicalDevice"):
        return "kInstance"
    if first in ("VkDevice", "VkQueue", "VkCommandBuffer"):
        return "kDevice"
    return "kGlobal"


def main():
    inc = sys.argv[1]
    commands = []
    seen = set()
    for header in HEADERS:
        text = open(os.path.join(inc, header), encoding="utf-8").read()
        for ret, name, params in PROTO.findall(text):
            if name in MANUAL or name in seen:
                continue
            seen.add(name)
            plist = [] if params.strip() in ("", "void") else [parse_param(p) for p in params.split(",")]
            commands.append((" ".join(ret.split()), name, plist))

    banner = "// Generated by direct/tools/gen_vulkan.py from the NDK's Vulkan headers. Do not edit.\n"

    g = [banner, "// %d commands\n" % len(commands)]
    for i, (ret, name, params) in enumerate(commands):
        decl = ", ".join("%s %s" % p for p in params) or "void"
        slots = ", ".join("u64(%s)" % p[1] for p in params) or "0"
        g.append('extern "C" VKAPI_ATTR %s VKAPI_CALL %s(%s) {\n' % (ret, name, decl))
        g.append("    const uint64_t a[] = {%s};\n" % slots)
        if ret == "void":
            g.append("    axrb_vk_call(%d, a);\n}\n" % i)
        else:
            g.append("    return from_u64<%s>(axrb_vk_call(%d, a));\n}\n" % (ret, i))
    g.append("\nstatic const VkCommand kCommands[] = {\n")
    for i, (ret, name, params) in enumerate(commands):
        g.append('    {"%s", reinterpret_cast<PFN_vkVoidFunction>(%s), %s},\n' % (name, name, level(params)))
    g.append("};\n")
    open(os.path.join(ROOT, "direct/guest/proxy/vk_thunks.inc"), "w", encoding="utf-8", newline="\n").write("".join(g))

    h = [banner, "// %d commands\n" % len(commands), "static const VkCommand kCommands[] = {\n"]
    for i, (ret, name, params) in enumerate(commands):
        h.append('    {"%s", %s, &Invoker<PFN_%s>::call},\n' % (name, level(params), name))
    h.append("};\n")
    open(os.path.join(ROOT, "direct/src/vk_entries.inc"), "w", encoding="utf-8", newline="\n").write("".join(h))
    print("%d commands" % len(commands))


main()
